    public function store(Request $request)
    {
        $validated = $request->validate([
            'name' => ['required', 'string', 'max:255'],
            'teacher_code' => ['required', 'string', 'max:50', 'unique:users,teacher_code'],
            'email' => ['required', 'string', 'email', 'max:255', 'unique:users'],
            'password' => ['required', 'confirmed', Rules\Password::defaults()],
            'phone' => ['nullable', 'string', 'max:20'],
            'photo' => ['nullable', 'image', 'mimes:jpeg,png,jpg', 'max:2048'],
            'address' => ['nullable', 'string', 'max:500'],
            'bio' => ['nullable', 'string', 'max:500'],
            'subject' => ['nullable', 'string', 'max:255'],
            'start_time' => ['nullable', 'date_format:H:i'],
            'end_time' => ['nullable', 'date_format:H:i'],
        ]);

        $photoPath = null;
        if ($request->hasFile('photo')) {
            $photoPath = ImageOptimizer::store($request->file('photo'), 'profiles/' . $request->file('photo')->hashName());
        }

        $employeeCode = null;
        DB::transaction(function () use ($validated, $photoPath, &$employeeCode) {
            $user = User::create([
                'name' => $validated['name'],
                'teacher_code' => $validated['teacher_code'],
                'email' => $validated['email'],
                'password' => Hash::make($validated['password']),
                'role' => 'guru',
                'photo' => $photoPath,
                'phone' => $validated['phone'] ?? null,
                'address' => $validated['address'] ?? null,
                'bio' => $validated['bio'] ?? null,
                'subject' => $validated['subject'] ?? null,
                'start_time' => $validated['start_time'] ?? '07:30',
                'end_time' => $validated['end_time'] ?? '16:00',
                'is_active' => true,
            ]);

            $user->generateQrCode();

            // Create Teacher record (employee_code auto-generated by model)
            $teacher = Teacher::create([
                'user_id' => $user->id,
                'name' => $validated['name'],
                'email' => $validated['email'],
                'phone' => $validated['phone'] ?? null,
                'address' => $validated['address'] ?? null,
                'major_specialty' => $validated['subject'] ?? null,
                'is_active' => true,
            ]);

            $employeeCode = $teacher->employee_code;
        });

        // Send notification
        $admins = User::whereIn('role', ['admin', 'operator'])->get();
        foreach ($admins as $admin) {
            /** @var User $admin */
            $admin->notify(new SystemNotification(
                "Data guru baru ({$validated['name']}) berhasil ditambahkan dengan ID: {$employeeCode}.",
                'info',
                route('teachers.index')
            ));
        }

        try { ActivityLogService::teacherCreated(auth()->user(), $user); } catch (\Exception $e) {}

        return redirect()->route('teachers.index')->with('success', "Guru berhasil ditambahkan dengan ID: {$employeeCode}!");
    }

